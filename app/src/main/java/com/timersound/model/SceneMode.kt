package com.timersound.model

import kotlinx.serialization.Serializable

/** Способ запуска звуков сценария. */
@Serializable
enum class SceneMode {
    REPEAT, ONCE_TIME, INTERVAL, RANDOM;

    /**
     * Короткое отображаемое имя для чипа режима — одно-два слова.
     *
     * Длинные подписи («Бесконечно, каждые …») не влезали в строку из четырёх чипов:
     * последние сжимались до ~100 px, подпись переносилась по буквам и строка вырастала
     * до 1100+ px — выглядело как огромный зазор между именем и полями времени.
     * Детали режима (интервал, окно, количество) видны в полях ниже и в сводке карточки.
     */
    val label: String
        get() = when (this) {
            REPEAT -> "Повтор"
            ONCE_TIME -> "Один раз"
            INTERVAL -> "N раз"
            RANDOM -> "Случайно"
        }
}
